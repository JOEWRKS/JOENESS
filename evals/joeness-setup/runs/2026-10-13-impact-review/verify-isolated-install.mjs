import {readFileSync,writeFileSync,mkdtempSync,existsSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {spawnSync} from 'node:child_process';
import assert from 'node:assert/strict';
const here=fileURLToPath(new URL('.',import.meta.url)),repo=resolve(here,'../../../..');
const temp=mkdtempSync(join(tmpdir(),'joeness-f05-install-'));
const sha=p=>createHash('sha256').update(readFileSync(p)).digest('hex');
const manifest=JSON.parse(readFileSync(join(repo,'vendor/source-manifest.json')));
const personal='C:/Users/tjdwo/.codex';
const watched=[...manifest.publicSkills[0].files.map(f=>'skills/joeness-setup/'+f.path),'joeness-skills-state.json','AGENTS.md','config.toml'];
const snapshot=()=>Object.fromEntries(watched.map(p=>[p,existsSync(join(personal,p))?sha(join(personal,p)):'absent']));
const before=snapshot();
const invoke=mode=>{
 const command=['powershell.exe','-NoProfile','-ExecutionPolicy','Bypass','-File',join(repo,'JOENESS.ps1'),'-'+mode,'-CodexHome',temp];
 const r=spawnSync(command[0],command.slice(1),{encoding:'utf8'});assert.ifError(r.error);
 return {command,exit:r.status,output:JSON.parse(r.stdout.trim()),stderr:r.stderr};
};
const apply=invoke('Apply'),check=invoke('Check');
assert.equal(apply.exit,0);assert.equal(check.output.status,'current');
const installed=manifest.publicSkills[0].files.map(f=>({path:f.path,expected:f.sha256,actual:sha(join(temp,'skills/joeness-setup',f.path))}));
assert.ok(installed.every(f=>f.actual===f.expected));
const cli=join(temp,'skills/joeness-setup/scripts/impact-review.mjs');
const command=[process.execPath,join(here,'verify-actual-producer.mjs'),'--limited'];
const replay=spawnSync(command[0],command.slice(1),{encoding:'utf8',env:{...process.env,JOENESS_TEST_IMPACT_CLI:cli,JOENESS_TEST_GATE_CLI:join(temp,'skills/joeness-setup/scripts/review-gate.mjs')}});assert.ifError(replay.error);
const after=snapshot();
const evidence={type:'isolated-installed-consumer-not-personal-install',root:temp,manifest_sha256:sha(join(repo,'vendor/source-manifest.json')),apply,check,installed,replay:{command,cli,exit:replay.status,stdout:replay.stdout,stderr:replay.stderr},personal_before:before,personal_after:after,personal_unchanged:JSON.stringify(before)===JSON.stringify(after),retained_for_review:true};
writeFileSync(join(here,process.argv[2]||'isolated-install.json'),JSON.stringify(evidence,null,2)+'\n');
assert.equal(replay.status,0);assert.ok(evidence.personal_unchanged);
console.log(JSON.stringify({installed_files:installed.length,replay_exit:replay.status,personal_unchanged:evidence.personal_unchanged,temporary_root:temp}));
